"""Copy original SQLite tables into isolated PostgreSQL schemas atomically."""
from contextlib import closing
import hashlib
import json
from pathlib import Path
import re
import sqlite3
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.utils.postgres import connect_postgres
from psycopg import sql

SOURCES = [('claim_verification','claim_verification.sqlite'), ('kipris','kipris_evidence_cache.sqlite')]

def digest(rows):
    result=hashlib.sha256()
    for row in rows:
        result.update(json.dumps(list(row),ensure_ascii=False,separators=(',',':')).encode())
        result.update(b'\n')
    return result.hexdigest()

def main():
    report=[]
    try:
        with connect_postgres() as pg:
            with pg.cursor() as target:
                for schema,filename in SOURCES:
                    source=ROOT/'Data_List_Claim_Verification'/filename
                    with closing(sqlite3.connect(source.as_uri()+'?mode=ro',uri=True)) as db:
                        if db.execute('PRAGMA integrity_check').fetchone()[0]!='ok' or db.execute('PRAGMA foreign_key_check').fetchall():
                            raise ValueError('Source database integrity failure')
                        # Refuse an existing schema; never overwrite target data.
                        target.execute('SELECT 1 FROM pg_namespace WHERE nspname=%s',(schema,))
                        if target.fetchone():
                            raise ValueError('Target schema already exists: '+schema)
                        target.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(schema)))
                        target.execute(sql.SQL('SET LOCAL search_path TO {}, public').format(sql.Identifier(schema)))
                        tables=db.execute("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY rowid").fetchall()
                        tables=[(n,d) for n,d in tables if not n.startswith('patent_search')]
                        for name,ddl in tables:
                            ddl=re.sub(r'\bINTEGER PRIMARY KEY\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',ddl,flags=re.I)
                            ddl=re.sub(r'\bINTEGER\b','BIGINT',ddl,flags=re.I)
                            ddl=re.sub(r'\bREAL\b','DOUBLE PRECISION',ddl,flags=re.I)
                            target.execute(ddl)
                            columns=db.execute('PRAGMA table_info("'+name+'")').fetchall()
                            names=[r[1] for r in columns]
                            primary=[r[1] for r in sorted(columns,key=lambda x:x[5]) if r[5]]
                            statement=sql.SQL('COPY {} ({}) FROM STDIN').format(sql.Identifier(schema,name),sql.SQL(',').join(map(sql.Identifier,names)))
                            with target.copy(statement) as copy:
                                for row in db.execute('SELECT * FROM "'+name+'"'):
                                    copy.write_row(row)
                            target.execute(sql.SQL('SELECT count(*) FROM {}').format(sql.Identifier(schema,name)))
                            count=target.fetchone()[0]
                            original=db.execute('SELECT count(*) FROM "'+name+'"').fetchone()[0]
                            if count!=original:raise ValueError('Count mismatch: '+name)
                            # Verify all column values, not just row counts.
                            order=primary or names
                            sqlite_order=','.join('"'+n+'"' for n in order)
                            expected=digest(db.execute('SELECT * FROM "'+name+'" ORDER BY '+sqlite_order))
                            with pg.cursor(name='verify_rows') as verify:
                                verify.execute(sql.SQL('SELECT * FROM {} ORDER BY {}').format(sql.Identifier(schema,name),sql.SQL(',').join(map(sql.Identifier,order))))
                                actual=digest(verify)
                            if actual!=expected:raise ValueError('Value verification mismatch: '+name)
                            for column in columns:
                                if column[2].upper()=='INTEGER' and column[5] and len(primary)==1:
                                    target.execute('SELECT pg_get_serial_sequence(%s,%s)',(schema+'.'+name,column[1]))
                                    sequence=target.fetchone()[0]
                                    if sequence:
                                        target.execute(sql.SQL('SELECT max({}) FROM {}').format(sql.Identifier(column[1]),sql.Identifier(schema,name)))
                                        maximum=target.fetchone()[0]
                                        target.execute('SELECT setval(%s,%s,%s)',(sequence,maximum or 1,maximum is not None))
                            report.append({'schema':schema,'table':name,'rows':count,'sha256':actual})
                            print(f'{schema}.{name}: {count} verified',flush=True)
                        for (ddl,) in db.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"):
                            if 'patent_search' not in ddl:target.execute(ddl)
                        for (ddl,) in db.execute("SELECT sql FROM sqlite_master WHERE type='view' AND sql IS NOT NULL"):
                            if 'v_claim_review_queue' in ddl:
                                ddl=ddl.replace('GROUP BY c.claim_id','GROUP BY c.claim_id, p.product_name')
                            target.execute(ddl)
                target.execute('CREATE INDEX idx_kipris_patents_title ON kipris.patents(title)')
        output=ROOT/'data/postgres_migration_report.json'
        output.write_text(json.dumps({'status':'complete','tables':report},ensure_ascii=False,indent=2),encoding='utf-8')
        print('Migration committed. Report: data/postgres_migration_report.json')
        return 0
    except Exception as exc:
        print('Migration not committed: '+type(exc).__name__+'. No credentials printed.')
        if isinstance(exc,ValueError):print(str(exc))
        return 1

if __name__=='__main__':raise SystemExit(main())
