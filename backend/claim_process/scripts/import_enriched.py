"""Stream the enriched SQLite database into an isolated PostgreSQL schema.

Usage: python claim_process/scripts/import_enriched.py --source <enriched sqlite> --dsn 'host=... port=... dbname=... user=...'
Uses psql/PGPASSWORD/.pgpass for authentication; never pass passwords in --dsn.
Existing schemas are never overwritten. All target changes commit together.
"""
import argparse
import os
import re
import shutil
import sqlite3
import subprocess
import tempfile
from pathlib import Path

ORDER = ['products', 'ingredients', 'diseases', 'claims', 'evidence',
         'claim_evidence_links', 'dataset_registry']

def ident(value):
    return '"' + value.replace('"', '""') + '"'

def field(value):
    if value is None:
        return r'\N'
    return str(value).replace('\\', '\\\\').replace('\t', r'\t').replace('\n', r'\n').replace('\r', r'\r')

def emit(db, stream, schema):
    def sql(statement):
        stream.write(statement + '\n')
    sql('BEGIN;')
    sql("SET LOCAL client_encoding TO 'UTF8';")
    sql('SET LOCAL standard_conforming_strings = on;')
    sql('CREATE SCHEMA ' + ident(schema) + ';')
    sql('SET LOCAL search_path TO ' + ident(schema) + ', pg_catalog;')
    tables = dict(db.execute("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"))
    if set(tables) != set(ORDER):
        raise ValueError('Unexpected source tables; review dependency order')
    for name in ORDER:
        ddl = re.sub(r'\bINTEGER PRIMARY KEY\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', tables[name], flags=re.IGNORECASE)
        ddl = re.sub(r'\bINTEGER\b', 'BIGINT', ddl, flags=re.IGNORECASE)
        ddl = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', ddl, flags=re.IGNORECASE)
        sql(ddl + ';')
        columns = list(db.execute('PRAGMA table_info(' + ident(name) + ')'))
        sql('COPY ' + ident(name) + ' (' + ','.join(ident(c[1]) for c in columns) + ') FROM STDIN;')
        count = 0
        for row in db.execute('SELECT * FROM ' + ident(name)):
            if any(isinstance(v, bytes) or (isinstance(v, str) and '\x00' in v) for v in row):
                raise ValueError('Unsupported binary or NUL value in ' + name)
            sql('\t'.join(field(v) for v in row))
            count += 1
        sql(r'\.')
        sql("DO $$ BEGIN IF (SELECT count(*) FROM " + ident(name) + ') <> ' + str(count) + " THEN RAISE EXCEPTION 'Row count mismatch'; END IF; END $$;")
        for col in columns:
            if col[2].upper() == 'INTEGER' and col[5]:
                relation = ident(schema) + '.' + ident(name)
                # Names come from the inspected, fixed source schema.
                relation_literal = relation.replace("'", "''")
                column_literal = col[1].replace("'", "''")
                sql("SELECT setval(pg_get_serial_sequence('" + relation_literal + "','" + column_literal + "'), COALESCE(max(" + ident(col[1]) + '),1), max(' + ident(col[1]) + ') IS NOT NULL) FROM ' + ident(name) + ';')
        print(name + ': ' + str(count) + ' rows streamed', flush=True)
    for (ddl,) in db.execute("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"):
        sql(ddl + ';')
    for (ddl,) in db.execute("SELECT sql FROM sqlite_master WHERE type='view' AND sql IS NOT NULL"):
        ddl = ddl.replace('GROUP BY c.claim_id', 'GROUP BY c.claim_id, p.product_name')
        sql(ddl + ';')
    sql('COMMIT;')
    stream.flush()

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--schema', default='claim_verification_enriched')
    parser.add_argument('--dsn', help='PostgreSQL connection string without password')
    parser.add_argument('--export', type=Path, help='Export psql-compatible SQL instead of connecting')
    args = parser.parse_args()
    if not args.dsn and not args.export:
        parser.error('Specify --dsn or --export')
    with sqlite3.connect(args.source.resolve().as_uri() + '?mode=ro', uri=True) as db:
        db.execute('BEGIN')
        if db.execute('PRAGMA integrity_check').fetchone()[0] != 'ok':
            raise ValueError('SQLite integrity check failed')
        if db.execute('PRAGMA foreign_key_check').fetchone():
            raise ValueError('SQLite foreign key check failed')
        if args.export:
            with args.export.open('x', encoding='utf-8', newline='\n') as output:
                emit(db, output, args.schema)
            print('Export complete: ' + str(args.export))
            return
        psql = shutil.which('psql')
        if not psql:
            raise RuntimeError('psql is required')
        env = dict(os.environ)
        env.setdefault('PGCONNECT_TIMEOUT', '10')
        with tempfile.TemporaryFile(mode='w+', encoding='utf-8') as log:
            process = subprocess.Popen([psql, '-X', '-w', '--set=ON_ERROR_STOP=1', '--dbname', args.dsn], stdin=subprocess.PIPE, stdout=log, stderr=log, text=True, encoding='utf-8', env=env)
            try:
                emit(db, process.stdin, args.schema)
                process.stdin.close()
                if process.wait() != 0:
                    log.seek(0)
                    raise RuntimeError('PostgreSQL import rolled back:\n' + log.read()[-3000:])
            except BaseException:
                if process.stdin and not process.stdin.closed:
                    process.stdin.close()
                process.wait()
                raise
        print('Committed: schema ' + args.schema + '. All table row counts verified.')

if __name__ == '__main__':
    main()
