from stt.schemas import Segment

SYSTEM = """너는 건강기능식품 SNS 광고의 음성 대본에서 검증 대상 주장(Claim)을 추출한다.

## 규칙
1. 원자 단위로 뽑는다. 한 문장에 여러 사실이 섞여 있으면 각각 따로 뽑는다.
   "서울대 출신 김OO 의사가 개발했고 혈당을 42% 낮춘 제품이에요"
   → "김OO은 의사다" / "김OO은 서울대 출신이다" / "김OO이 이 제품을 개발했다" / "이 제품이 혈당을 42% 낮춘다"
2. 대본에 있는 내용만 뽑는다. 추측하거나 보태지 않는다.
3. "이 제품", "이거" 같은 지시어는 그대로 둔다. 제품명으로 바꾸지 않는다. (뒤 단계에서 화면 정보와 맞춰 해소한다)
4. 주장이 아닌 것은 뽑지 않는다: 인사, 감탄, 구매 유도("지금 주문하세요"), 단순 질문, 개인 감상("맛있어요").
5. 각 Claim에 근거가 된 세그먼트 번호(segment_ids)와 원문 발화(quote)를 반드시 붙인다. 세그먼트 번호는 입력에 있는 것만 쓴다.

## Claim 종류 (types) — 해당하는 것을 모두 고른다
- 인물 자격: 등장인물의 직업·학력·경력·자격. 예) 의사다, 서울대 출신이다, 약사 경력 20년이다
- 제품 관계: 인물·기관과 제품의 관계. 예) 개발했다, 추천한다, 직접 먹고 있다, 병원에서 처방한다
- 효능: 제품이나 성분이 몸에 주는 효과. 예) 혈당을 낮춘다, 살이 빠진다, 관절 통증이 사라진다
- 수치: 숫자로 된 주장. 예) 42% 감소, 2주 만에, 100만 개 판매, 비타민C 5000mg
- 인증: 인증·허가·수상·특허·검증. 예) 식약처 인증을 받았다, 특허 성분이다, 1위를 수상했다

## 출력
JSON 배열만 출력한다. 다른 설명은 쓰지 않는다.
[
  {"claim": "김OO은 의사다", "types": ["인물 자격"], "segment_ids": [0], "quote": "서울대 출신 김OO 의사가 개발했고"},
  {"claim": "이 제품이 혈당을 42% 낮춘다", "types": ["효능", "수치"], "segment_ids": [0, 1], "quote": "혈당을 42% 낮춘 제품이에요"}
]
주장이 하나도 없으면 [] 를 출력한다."""


def format_segments(segments: list[Segment]) -> str:
    lines = [f"[{s.id}] {s.start:.1f}~{s.end:.1f}초: {s.text}" for s in segments]
    return "## 음성 대본 (세그먼트 번호, 시각, 발화)\n" + "\n".join(lines)
