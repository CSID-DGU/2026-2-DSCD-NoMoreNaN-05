from ..keyframe import Keyframe

PROMPT = """이 이미지는 건강기능식품 SNS 광고 영상의 {timestamp:.1f}초 프레임이다.
화면에 보이는 것 중 검증 대상이 되는 주장(Claim)을 추출한다.
광고 내용을 요약하거나 재작성하지 않고, 제품·원료의 효능, 기능성, 성분, 인증, 복용 결과 등
구매 판단에 영향을 주는 사실 주장만 뽑는다.

## 뽑는 대상
- 화면 글자 (자막, 문구, 면책 문구, 포장 속 제품명·성분명)
- 전후 비교 사진 (before/after)
- 인증 마크, 수상 로고, 특허 표시
- 기기 화면의 숫자 (혈당계, 체중계 등)
- 전문가 복장 (흰 가운, 약사 가운 등) — 등장인물이 전문가처럼 보이게 하는 요소

## 추출 규칙
1. 화면에 실제로 보이는 것만 뽑는다. 추측하거나 보태지 않는다.
2. 화면 글자는 원문 그대로 text에 옮긴다. 요약·재작성하지 않는다.
   아래 OCR 결과를 참고하되, 이미지와 다르면 이미지를 따른다.
3. 글자가 아닌 것(전후 사진, 인증 마크, 기기 숫자, 복장)은 보이는 그대로 짧게 서술한다.
   예) "혈당 -42% 막대그래프", "식약처 인증 마크", "등장인물이 흰 가운을 입고 있다"
4. 한 문구에 여러 독립적인 사실 주장이 있으면 최소 의미 단위로 분리한다. 같은 대상·조건을 공유하면 지나치게 잘게 나누지 않는다.
5. 기간, 수치, 확정·강조 표현은 삭제하지 않는다.
6. 단순 홍보 문구, CTA("지금 구매"), 슬로건, 감탄은 제외한다.
7. "개인차가 있을 수 있습니다" 같은 면책 문구는 뽑는다 (types는 빈 배열, scope는 OUT_OF_SCOPE).
8. 대상이 명확하면 target에 제품명·원료명·브랜드명을 적는다. 화면에 제품 포장이 보이면 그 제품명. 불명확하면 null.
9. 식약처 공식 데이터(제품 등록, 기능성 원료, 성분·함량, 질병 표현)로 1차 검증 가능하면 IN_SCOPE, 아니면 OUT_OF_SCOPE.

## Claim 종류 (types) — 해당하는 것을 모두 고른다. 없으면 빈 배열
- 인물 자격: 흰 가운, "의사", "약사", 학위·경력 표시
- 제품 관계: 인물과 제품을 잇는 표현 (개발, 추천, 복용)
- 효능: 효과를 나타내는 그림·글자 (전후 사진, "혈당 감소")
- 수치: 숫자로 된 주장 (-42%, 2주, 5000mg, 기기 화면 숫자)
- 인증: 인증 마크, 수상, 특허, "식약처 인정"

## 이 프레임의 OCR 결과
{ocr}

## 출력
JSON 배열만 출력한다. 다른 설명은 쓰지 않는다.
[
  {{"text": "혈당 -42%", "target": "ABC 혈당케어", "scope": "IN_SCOPE", "types": ["효능", "수치"]}},
  {{"text": "등장인물이 흰 가운을 입고 있다", "target": null, "scope": "OUT_OF_SCOPE", "types": ["인물 자격"]}},
  {{"text": "개인차가 있을 수 있습니다", "target": null, "scope": "OUT_OF_SCOPE", "types": []}}
]
주장이 하나도 없으면 [] 를 출력한다."""


def format_prompt(kf: Keyframe) -> str:
    return PROMPT.format(timestamp=kf.timestamp, ocr=kf.text or "(없음)")
