"""면책 문구인지 확인한다. 면책 문구는 조항 판정을 하지 않고 DISCLAIMER 라벨만 붙인다.

면책 문구에는 "질병", "예방", "천식" 같은 말이 들어 있어 그대로 두면 1호 후보로 잡힌다.
NLI가 부정문("~의약품이 아닙니다")을 놓치면 위반이 나온다. 그래서 판정 전에 거른다.

아래 다섯 문형만 본다. 문장 전체가 면책 문형이어야 한다. 다른 말이 붙어 있으면 면책으로 보지 않고
평소대로 판정한다. 위반 주장이 면책으로 빠지는 것을 막기 위해서다.

- 의약품 아님 고지: "본 제품은 질병의 예방 및 치료를 위한 의약품이 아닙니다"
- 섭취 주의사항: "이상사례 발생 시 섭취를 중단하고 전문가와 상담하십시오", "임산부는 섭취에 주의하십시오"
- 시험결과 일반화 제한: "시험결과는 모든 사람에게 동일하게 적용되는 것은 아닙니다"
- 개인차 고지: "개인에 따라 차이가 있을 수 있습니다"
- 정보 무관 고지: "본 정보는 제품과 관련 없는 내용입니다"
"""

import re

DISCLAIMER = "DISCLAIMER"

# 면책 문구 앞에 오는 조건절("이상사례 발생 시", "질환이 있거나 의약품 복용 시")은 자유롭게 받되,
# 효능을 말하는 단어가 끼어 있으면 받지 않는다. "암을 치료하며 개인에 따라 차이가 있을 수 있습니다"를
# 면책으로 넘기면 치료 주장이 판정 없이 빠진다.
_CLAIM_WORD = r"(치료|예방|방지|개선|완화|효과|효능|도움|좋|낫|나아|완치|해결|감소|증가|강화|회복|억제|없애|잡아)"


def _free(n: int) -> str:
    """효능 단어가 없는 임의 문자열 최대 n자."""
    return rf"(?:(?!{_CLAIM_WORD})[^.!?]){{0,{n}}}"


_NOT_DRUG = (r"((본|이|해당)\s*)?(제품은\s*)?(질병의\s*예방\s*(및|과|또는)\s*치료를\s*위한\s*)?"
             r"의약품이\s*아(닙니다|님|니다)")
_CONSULT = (_free(80) + r"(시|경우|분은|분|때)\s*,?\s*(섭취\s*(전|전에|시)\s*|섭취를\s*중단하고\s*)?"
            r"(반드시\s*)?(전문가|의사|약사)(와|과|에게|와\s*꼭)\s*상담하(십시오|세요|시기\s*바랍니다)")
_CHECK_BEFORE = _free(80) + r"(확인하고|확인\s*후)\s*섭취하(시기\s*바랍니다|십시오|세요)"
_STOP = _free(80) + r"(시|경우)\s*,?\s*섭취를\s*중단하(십시오|세요|시기\s*바랍니다)"
_CAUTION = _free(80) + r"(은|는)\s*섭취에\s*주의하(십시오|세요|시기\s*바랍니다)"
_NOT_ALL = (_free(40) + r"결과[가는]?\s*모든\s*(사람|분)(에게|들에게)\s*동일(하게)?\s*(적용|나타)"
            r"[^.!?]{0,12}아(닙니다|님|니다)")
_INDIVIDUAL = (_free(40) + r"개인(에\s*따라|별로|차이?)" + _free(20)
               + r"(있을\s*수\s*있습니다|있습니다|있음|있을\s*수\s*있음|날\s*수\s*있습니다)")

_NOT_RELATED = (r"(건강정보\s*:\s*)?본\s*(정보|내용)[은는]\s*(본\s*)?제품과\s*(관련\s*없는|무관한)\s*"
                r"(내용|정보)입니다")

PATTERNS = [re.compile(p) for p in (_NOT_DRUG, _CONSULT, _CHECK_BEFORE, _STOP, _CAUTION, _NOT_ALL,
                                    _INDIVIDUAL, _NOT_RELATED)]

# "[섭취 시 주의사항]" 같은 머리말은 내용으로 치지 않는다.
_HEADER = re.compile(r"^\s*\[[^\]]{0,20}주의\s*사항\]\s*")

# 문장 앞뒤에 붙는 표시. "※", "*" 각주 기호와 문장부호는 내용으로 치지 않는다.
_EDGE = re.compile(r"^[\s※*·\-]+|[\s.!?]+$")
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+|\n+")


def is_disclaimer(text: str) -> bool:
    """문장(여러 문장이면 전부)이 면책 문형과 처음부터 끝까지 맞으면 True."""
    sentences = [_EDGE.sub("", s) for s in _SENTENCE_END.split(_HEADER.sub("", text))]
    sentences = [s for s in sentences if s]
    return bool(sentences) and all(any(p.fullmatch(s) for p in PATTERNS) for s in sentences)
