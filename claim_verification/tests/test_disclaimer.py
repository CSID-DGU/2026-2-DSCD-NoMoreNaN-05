import pytest

from claim_verification.disclaimer import is_disclaimer


@pytest.mark.parametrize("text", [
    # 의약품 아님 고지
    "본 제품은 질병의 예방 및 치료를 위한 의약품이 아닙니다.",
    "본 제품은 의약품이 아닙니다.",
    "이 제품은 질병의 예방 및 치료를 위한 의약품이 아닙니다",
    "질병의 예방 및 치료를 위한 의약품이 아닙니다.",
    # 섭취 주의사항
    "이상사례 발생 시 섭취를 중단하고 전문가와 상담하십시오.",
    "간·신장·심장질환, 알레르기 및 천식이 있거나 의약품 복용 시 전문가와 상담하십시오.",
    "신장질환이 있는 경우 섭취 전 전문가와 상담하십시오.",
    "특이 체질, 알레르기 체질이신 분은 반드시 원료(성분)를 확인하고 섭취하시기 바랍니다.",
    "[섭취 시 주의사항] 영·유아, 어린이, 임산부 및 수유부는 섭취에 주의하십시오. "
    "특정질환(알레르기 체질 등)이 있는 분은 섭취에 주의하십시오. "
    "이상사례 발생 시 섭취를 중단하고 전문가와 상담하십시오.",
    # 시험결과 일반화 제한
    "※ 시험결과는 모든 사람에게 동일하게 적용되는 것은 아닙니다.",
    "인체적용시험결과가 모든사람에게 동일적용되는 것은 아님",
    # 개인차 고지
    "모델의 주관적인 의견으로 개인차이가 있습니다",
    # 정보 무관 고지
    "건강정보: 본 정보는 제품과 관련 없는 내용입니다.",
])
def test_disclaimer(text):
    assert is_disclaimer(text)


@pytest.mark.parametrize("text", [
    "감기예방 및 초기감기 치료",
    "골다공증을 예방합니다",
    # 면책 문구 뒤에 주장이 붙으면 면책이 아니다
    "본 제품은 의약품이 아닙니다. 하지만 감기예방 효과는 탁월!",
    "감기예방 효과 탁월! 본 제품은 질병의 예방 및 치료를 위한 의약품이 아닙니다",
    # 한 문장 안에 효능 주장이 섞여도 면책이 아니다 (Codex 리뷰)
    "본 제품은 암을 치료하지만 의약품이 아닙니다.",
    "암을 치료하며 개인에 따라 차이가 있을 수 있습니다.",
    "관절 통증이 감소하며 이상사례 발생 시 전문가와 상담하십시오.",
    "피로 개선 효과 시험 결과가 모든 사람에게 동일하게 적용되는 것은 아닙니다.",
    "인체적용시험 결과 관절 통증 감소",
    "",
])
def test_not_disclaimer(text):
    assert not is_disclaimer(text)
