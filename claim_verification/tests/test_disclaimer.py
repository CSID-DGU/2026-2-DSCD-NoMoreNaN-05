@pytest.mark.parametrize("text", [
    "암을 치료하며 모든 사람에게 적용되는 것은 아닙니다",
    "제품이 아닌 원료로 암을 치료합니다",
    "관절 개선 효과는 제품이 아닌 원료에 한함",
    "면역력이 좋아져 과량 섭취하지 않도록 주의하십시오",
    "알레르기 정보 : 대두·쇠고기 함유",
    "임산부·수유부도 안심하고 섭취!",
])
def test_claims_are_not_taken_for_added_forms(text):
    assert not is_disclaimer(text)
